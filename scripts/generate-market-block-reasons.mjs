#!/usr/bin/env node
// Regenerates packages/core/types/market-block-reasons.ts from
// server/internal/handler/market_block_reasons.json (the single source of truth).
//
// Run via `pnpm generate:market-block-reasons`. CI re-runs the generator and
// `git diff --exit-code`s the output, so the JSON and TS sides cannot drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(repoRoot, "server/internal/handler/market_block_reasons.json");
const tsPath = resolve(repoRoot, "packages/core/types/market-block-reasons.ts");

const data = JSON.parse(readFileSync(jsonPath, "utf8"));

if (!Array.isArray(data.reasons) || data.reasons.length === 0) {
  throw new Error(`market_block_reasons.json: expected a non-empty top-level "reasons" array`);
}

const seen = new Set();
for (const reason of data.reasons) {
  if (typeof reason !== "string" || !/^[a-z][a-z0-9_]*$/.test(reason)) {
    throw new Error(`market_block_reasons.json: reasons must be snake_case strings, got ${JSON.stringify(reason)}`);
  }
  if (reason === "unknown") {
    throw new Error(`market_block_reasons.json: "unknown" is the client's name for a reason it cannot read`);
  }
  if (seen.has(reason)) {
    throw new Error(`market_block_reasons.json: duplicate reason ${JSON.stringify(reason)}`);
  }
  seen.add(reason);
}

const lines = [
  "// AUTO-GENERATED by scripts/generate-market-block-reasons.mjs.",
  "// Do not edit by hand — edit server/internal/handler/market_block_reasons.json",
  "// and run `pnpm generate:market-block-reasons`.",
  "",
  "export const PREFLIGHT_BLOCK_REASONS = [",
  ...data.reasons.map((reason) => `  ${JSON.stringify(reason)},`),
  "] as const;",
  "",
];

writeFileSync(tsPath, lines.join("\n"));
